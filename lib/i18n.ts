export type Locale = keyof typeof locales;
export type TranslationKeys = typeof locales.en;

/**
 * Picks the right plural form for the onboarding question count.
 *
 * The onboarding heading must never hardcode a step count: the number is
 * derived from the implemented questionnaire so adding or removing a
 * conditional question cannot leave copy claiming a different total.
 */
export function questionCountWord(count: number, locale: Locale): string {
  const section = (locales[locale].onboarding as unknown as Record<string, string>);
  if (locale === "en") {
    return count === 1 ? section.questionWordOne : section.questionWordMany;
  }
  // Russian: 1 вопрос, 2–4 вопроса, 5+ вопросов (with the 11–14 exception).
  const mod100 = count % 100;
  const mod10 = count % 10;
  if (mod100 >= 11 && mod100 <= 14) return section.questionWordMany;
  if (mod10 === 1) return section.questionWordOne;
  if (mod10 >= 2 && mod10 <= 4) return section.questionWordFew;
  return section.questionWordMany;
}
